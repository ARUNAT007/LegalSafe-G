"""
Database initialisation and connection management for LegalSafe-G.

Tables:
  documents   — uploaded document metadata
  results     — full pipeline result JSON (keyed by UUID result_id)
  experiments — evaluation run records
"""

import os
import sqlite3
import logging
from contextlib import contextmanager

logger = logging.getLogger(__name__)


def get_db_path(app=None) -> str:
    """Return the configured SQLite database path."""
    if app:
        return app.config.get('DATABASE_PATH', 'legalsafe.db')
    from config import Config
    return Config.DATABASE_PATH


@contextmanager
def get_db(app=None):
    """
    Context manager that yields a SQLite connection.

    Automatically commits on success and rolls back on exception.
    Uses sqlite3.Row for dict-like row access.
    """
    db_path = get_db_path(app)
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
        conn.commit()
    except Exception as exc:
        conn.rollback()
        logger.error(f'Database error: {exc}')
        raise
    finally:
        conn.close()


def init_db(app) -> None:
    """
    Initialise all database tables.

    Called once at application startup. Uses CREATE TABLE IF NOT EXISTS
    so it is safe to call on an existing database.
    """
    db_path = get_db_path(app)

    # Ensure the directory exists (handles paths like 'data/legalsafe.db')
    db_dir = os.path.dirname(db_path)
    if db_dir:
        os.makedirs(db_dir, exist_ok=True)

    logger.info(f'Initialising database at: {db_path}')

    with app.app_context():
        with get_db(app) as db:
            # ── documents ────────────────────────────────────────────────────
            db.execute('''
                CREATE TABLE IF NOT EXISTS documents (
                    id          TEXT PRIMARY KEY,
                    filename    TEXT NOT NULL,
                    uploaded_at TEXT NOT NULL,
                    status      TEXT NOT NULL DEFAULT 'uploaded',
                    file_path   TEXT NOT NULL
                )
            ''')

            # ── results ──────────────────────────────────────────────────────
            # Stores the entire pipeline result as a JSON blob.
            # The result_id is a UUID generated by the simplification route.
            db.execute('''
                CREATE TABLE IF NOT EXISTS results (
                    id          TEXT PRIMARY KEY,
                    document_id TEXT NOT NULL,
                    created_at  TEXT NOT NULL,
                    result_json TEXT NOT NULL,
                    FOREIGN KEY (document_id) REFERENCES documents (id)
                )
            ''')

            # ── experiments ──────────────────────────────────────────────────
            db.execute('''
                CREATE TABLE IF NOT EXISTS experiments (
                    id           TEXT PRIMARY KEY,
                    document_id  TEXT,
                    created_at   TEXT NOT NULL,
                    metrics_json TEXT,
                    FOREIGN KEY (document_id) REFERENCES documents (id)
                )
            ''')

    logger.info('Database tables ready.')
